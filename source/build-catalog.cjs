/* Re-index existing generated themes; never regenerate or overwrite theme files. */
const fs = require('fs'), path = require('path'), vm = require('vm'), crypto = require('crypto');
const labels = { '01_neon_pair':'霓虹赛道', '02_redline':'红线赛车', '03_road_king':'公路之王', '04_nine_pack':'九款仪表', '05_quad_color':'四色双栏', '06_video_rpm':'视频转速', '07_home_expansion':'默认仪表同款' };
const catalog = [], generated = new Map();
for (const dir of fs.readdirSync(__dirname).sort()) {
  const source = path.join(__dirname, dir, 'theme-data.js');
  if (!fs.existsSync(source)) continue;
  const context = { window: {} };
  vm.runInNewContext(fs.readFileSync(source, 'utf8'), context, { timeout: 5000 });
  const globalName = Object.keys(context.window).find(k => k.endsWith('_VARIANTS'));
  if (!globalName) continue;
  const assetsName = Object.keys(context.window).find(k => k.endsWith('_ASSETS')) || '';
  const samplesName = Object.keys(context.window).find(k => k.endsWith('_SAMPLES')) || '';
  const metaName = Object.keys(context.window).find(k => k.endsWith('_META')) || '';
  function visit(value, keys) {
    const variants = Object.entries(value).filter(([, v]) => v && v.design && v.json && v.pack);
    if (!variants.length) { for (const [k, v] of Object.entries(value)) visit(v, [...keys, k]); return; }
    const base = variants[0][1], pngs = fs.readdirSync(path.join(__dirname, dir)).filter(n => n.endsWith('.png'));
    const stem = path.basename(base.json, '.json');
    const preview = pngs.find(n => n.startsWith(stem + '_')) || pngs.find(n => keys.includes('speed') ? n.startsWith('车速') : keys.includes('gear') ? n.startsWith('挡位') : n === '效果预览.png');
    if (!preview) throw Error('Theme preview missing: ' + dir + '/' + stem);
    const item = { id: [dir, ...keys].join('/'), series: labels[dir] || dir.replace(/^\d+_/, ''), name: base.design.meta?.name || stem,
      folder: 'themes/' + dir, source: 'themes/' + dir + '/theme-data.js', globalName, assetsName, samplesName, metaName, keys,
      preview: 'themes/' + dir + '/' + preview, variants: variants.map(([key, v]) => {
        for (const file of [v.json, v.pack]) if (!fs.existsSync(path.join(__dirname, dir, file))) throw Error('Missing theme file: ' + file);
        return { key, width: v.design.canvas.designW, height: v.design.canvas.designH, pack: v.pack };
      }) };
    const assetIds = new Set(variants.flatMap(([,v]) => (v.design.assets || []).map(a => a.id)));
    const assets = Object.fromEntries(Object.entries(context.window[assetsName] || {}).filter(([id]) => assetIds.has(id)));
    const samples = context.window[samplesName] || (context.window[metaName] || []).find(m => m.key === keys[0])?.samples || {};
    const payload = { variants: Object.fromEntries(variants), assets, samples };
    const chunk = 'window.registerIcarTheme(' + JSON.stringify(item.id) + ',' + JSON.stringify(payload) + ');\n';
    const filename = [dir,...keys].join('_') + '.js';
    item.source = 'themes/_library/' + filename; item.bytes = Buffer.byteLength(chunk);
    item.contentHash = crypto.createHash('sha256').update(chunk).digest('hex');
    generated.set(path.join(__dirname,'_library',filename),chunk); catalog.push(item);
  }
  visit(context.window[globalName], []);
}
const output = '/* Generated by node themes/build-catalog.cjs; original themes remain untouched. */\nwindow.ICAR_PROJECT_THEMES = ' + JSON.stringify(catalog, null, 2) + ';\n';
const file = path.join(__dirname, 'catalog.js');
generated.set(file,output);
if (process.argv.includes('--check')) {
  for (const [target,text] of generated) if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text) throw Error('Theme index/bundle is stale: ' + target);
} else for (const [target,text] of generated) { fs.mkdirSync(path.dirname(target),{recursive:true}); fs.writeFileSync(target,text); }
console.log(catalog.length + ' themes / ' + catalog.reduce((n, t) => n + t.variants.length, 0) + ' variants');
